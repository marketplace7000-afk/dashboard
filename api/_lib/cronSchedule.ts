/**
 * Расписание фонового сборщика — ОДНО место истины.
 *
 * Раньше интервал был записан в трёх местах независимо: планировщик в server.ts
 * ходил каждые 2 часа, гейты свежести считали от TTL, а /api/meta/status
 * рапортовал «раз в сутки». Клиент читает именно плашку статуса, поэтому
 * расхождение подрывало доверие к цифрам сильнее, чем сама задержка.
 */

/** Как часто сборщик делает проход. Проход идемпотентный: свежее не перезапрашивает. */
export const CRON_WARM_INTERVAL_MS = 2 * 60 * 60_000;

/**
 * Порог обновления «живых» датасетов (цены, отзывы, реклама, воронка).
 * Строго МЕНЬШЕ интервала прохода, иначе обновление проскакивает через раз:
 * с TTL 3ч при проходе раз в 2ч воронка реально обновлялась раз в ЧЕТЫРЕ часа.
 * Запас в 20 минут — на дрейф времени запуска.
 */
export const REFRESH_LIVE_MS = CRON_WARM_INTERVAL_MS - 20 * 60_000;
