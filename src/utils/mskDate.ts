/**
 * Даты периодов на фронте — ВСЕГДА по Москве.
 *
 * Зеркало api/_lib/mskDate.ts. Держать их согласованными обязательно: ключ
 * серверного кэша строится из дат запроса, и если сборщик считает окно по МСК,
 * а браузер по UTC, то с 00:00 до 03:00 МСК ключи расходятся — запрос падает
 * в STALE-NEAR и показывает данные чужого периода.
 *
 * Именно МСК, а не «локальное время браузера»: платформа готовится к
 * мультиарендности, а продавец может открыть её из любого часового пояса —
 * сутки же на WB и Ozon всегда московские.
 *
 * Москва — UTC+3 круглый год (перевода часов в РФ нет с 2014).
 */

const MSK_OFFSET_MS = 3 * 3_600_000;
const DAY_MS = 86_400_000;

/** МСК-дата YYYY-MM-DD, `back` дней назад (0 = сегодня по Москве). */
export function mskDate(back = 0): string {
  return new Date(Date.now() + MSK_OFFSET_MS - back * DAY_MS).toISOString().slice(0, 10);
}

/** МСК-дата для произвольного момента — для подписей на графиках по дням. */
export function mskDateOf(d: Date | number): string {
  const t = typeof d === 'number' ? d : d.getTime();
  return new Date(t + MSK_OFFSET_MS).toISOString().slice(0, 10);
}
