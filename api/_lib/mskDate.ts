/**
 * Даты периодов — ВСЕГДА по Москве.
 *
 * Зачем отдельный модуль: платформа торгует на WB и Ozon, а обе площадки считают
 * сутки по МСК. Раньше даты строились через `new Date().toISOString()` — то есть
 * в UTC. С 00:00 до 03:00 МСК это давало ВЧЕРАШНЮЮ дату: сборщик просил у WB
 * окно, заканчивающееся вчера, а клиент в кабинете видел уже сегодняшний день и
 * справедливо считал, что платформа занижает выручку (телемост 11.08).
 *
 * Проверено 14.08.2026 в момент аудита: UTC-дата 2026-08-13, МСК-дата 2026-08-14.
 *
 * Москва — UTC+3 круглый год (перевода часов в РФ нет с 2014), поэтому сдвиг
 * ровно на 3 часа корректен без таблицы переходов.
 */

const MSK_OFFSET_MS = 3 * 3_600_000;
const DAY_MS = 86_400_000;

/** МСК-дата YYYY-MM-DD, `back` дней назад (0 = сегодня по Москве). */
export function mskDate(back = 0): string {
  return new Date(Date.now() + MSK_OFFSET_MS - back * DAY_MS).toISOString().slice(0, 10);
}

/** МСК-момент в ISO — для методов, которым нужна не дата, а время (Ozon finance). */
export function mskIso(back = 0): string {
  return new Date(Date.now() - back * DAY_MS).toISOString();
}

/**
 * Номер МСК-суток (целое). Аналог `Math.floor(Date.now()/86_400_000)`, но
 * с московской границей суток. Нужен ключам кэша: окно считается как смещение
 * «сегодня минус конец периода», и если «сегодня» в UTC, а даты окна в МСК,
 * ночью смещение уезжает на единицу и ключ сборщика перестаёт совпадать
 * с ключом браузера.
 */
export function mskDayNumber(at: number = Date.now()): number {
  return Math.floor((at + MSK_OFFSET_MS) / DAY_MS);
}

/** Номер МСК-суток из строки YYYY-MM-DD. */
export function mskDayNumberOf(isoDay: string): number {
  return Math.floor(Date.parse(isoDay + 'T00:00:00Z') / DAY_MS);
}
