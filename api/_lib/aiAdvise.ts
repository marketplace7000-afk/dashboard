export async function aiAdvise(body: any) {
  const module = String(body?.module || '');
  const cfg = MODULE_PROMPTS[module];
  if (!cfg) return { ok: false, error: 'unknown_module', module };

  const context = body?.context;
  const ctxStr = JSON.stringify(context ?? {}, null, 1);
  if (!context || ctxStr.length < 10) {
    return {
      ok: true,
      module,
      advice: { verdict: 'Мало данных для анализа. Открой модуль с загруженными данными и повтори.', actions: [], warnings: [] },
    };
  }

  const prompt =
    `Модуль «${cfg.title}». ${cfg.focus}\n\n` +
    `Данные с экрана (JSON):\n${ctxStr.slice(0, 8000)}\n\n` +
    `Верни СТРОГО JSON:\n{\n` +
    `  "verdict": "1-2 предложения — главный вывод по модулю",\n` +
    `  "actions": [{"priority":"high|medium|low","text":"конкретный шаг","sku":"артикул если применим, иначе опусти"}],\n` +
    `  "warnings": ["риски/аномалии, если есть; иначе пустой массив"]\n` +
    `}\nБез текста вне JSON. Максимум 6 действий, самое важное — priority high. Ссылайся на реальные артикулы из данных.`;

  const { text } = await callAnthropic({
    system: ROLE,
    messages: [{ role: 'user', content: prompt }],
    max_tokens: 1100,
    temperature: 0.25,
    agent: `advise:${module}`,
  });

  const parsed = extractJson<Advice>(text);
  return { ok: true, module, advice: parsed ?? { verdict: '', actions: [], warnings: [], raw: text } };
}
